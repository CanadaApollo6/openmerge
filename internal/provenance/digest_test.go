func digestFixture(t *testing.T) ([]Commit, []Rule) {
	t.Helper()
	commits := []Commit{{"b", true, nil}, {"a", true, ParseGitTrailers("Entire-Checkpoint: abcdef012345")}}
	checkpoint, ci := expression(t, "checkpoint-present"), expression(t, "check-success = ci")
	rules := []Rule{
		{When: expression(t, "provenance = human"), Conditions: &ci}, // definitely false; omitted
		{When: expression(t, "provenance = agent"), Conditions: &checkpoint},
		{When: expression(t, "approved-reviews-by = bob"), Conditions: &ci, Approvals: &cp.Requirement{Selector: cp.Human, Count: 2}}, // mutable trigger; always retained
	}
	return commits, rules
}

func TestDeclarationDigestVectors(t *testing.T) {
	// Vectors are independently encoded and hashed with Python's compact JSON
	// and hashlib, not generated by the implementation under test.
	data, err := os.ReadFile("testdata/declaration-vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []struct{ Name, Canonical, SHA256 string }
	if err := json.Unmarshal(data, &vectors); err != nil {
		t.Fatal(err)
	}
	for _, v := range vectors {
		t.Run(v.Name, func(t *testing.T) {
			var commits []Commit
			var rules []Rule
			switch v.Name {
			case "empty":
			case "undeclared":
				commits = []Commit{{"a", true, nil}}
			case "potential-rules":
				commits, rules = digestFixture(t)
			default:
				t.Fatal("unknown vector")
			}
			got, err := CanonicalDeclarations(commits, true, rules)
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != v.Canonical {
				t.Fatalf("canonical\ngot  %s\nwant %s", got, v.Canonical)
			}
			digest, err := DeclarationDigest(commits, true, rules)
			if err != nil || digest != v.SHA256 {
				t.Fatalf("digest %s err %v want %s", digest, err, v.SHA256)
			}
		})
	}
}

func TestDeclarationDigestConservativeBinding(t *testing.T) {
	commits, rules := digestFixture(t)
	want, err := DeclarationDigest(commits, true, rules)
	if err != nil {
		t.Fatal(err)
	}
	before, _ := json.Marshal(commits)
	commits[0], commits[1] = commits[1], commits[0]
	commits[0].Declarations = append(commits[0].Declarations, commits[0].Declarations...)
	rules[0], rules[2] = rules[2], rules[0]
	got, err := DeclarationDigest(commits, true, rules)
	if err != nil || got != want {
		t.Fatalf("set order/dedup changed digest %s %v", got, err)
	}
	// Repeated evaluation with mutable reviews/checkpoints cannot enter this API.
	for _, value := range []cp.Truth{cp.Unknown, cp.False, cp.True} {
		inputs := DeclarationAttributes(commits, true)
		if value != cp.Unknown {
			inputs["checkpoint-present"] = condition.Bool(value == cp.True)
		}
		_ = EvaluateRequirements(expression(t, "draft"), nil, cp.Evaluation{}, inputs, rules, nil)
		got, err := DeclarationDigest(commits, true, rules)
		if err != nil || got != want {
			t.Fatal("gate evaluation churned digest")
		}
	}
	changed, changedRules := digestFixture(t)
	after, _ := json.Marshal(changed)
	if !reflect.DeepEqual(before, after) {
		t.Fatal("fixture mutated")
	}
	for _, mutate := range []func(){
		func() { changed[0].Declarations = ParseGitTrailers("Agent-Session: generic:one") },
		func() { changedRules[2].Approvals.Count = 3 },
		func() { changedRules[2].When = expression(t, "approved-reviews-by = alice") },
		func() { changedRules[1].When = expression(t, "#agent-commits > 0") },
	} {
		changed, changedRules = digestFixture(t)
		mutate()
		got, err := DeclarationDigest(changed, true, changedRules)
		if err != nil || got == want {
			t.Fatal("changed declaration/requirement not bound", err)
		}
	}
	// A definitely-false rule's requirement can change without changing this
	// narrower digest; effective policy digest remains independently responsible.
	changed, changedRules = digestFixture(t)
	changedRules[0].Conditions = nil
	changedRules[0].Approvals = &cp.Requirement{Selector: cp.Human, Count: 9}
	got, err = DeclarationDigest(changed, true, changedRules)
	if err != nil || got != want {
		t.Fatal("definitely false rule bound", err)
	}
}

func TestDeclarationDigestRejectsIncompleteAndMutableOutcomes(t *testing.T) {
	for _, tc := range []struct {
		commits  []Commit
		complete bool
	}{
		{nil, false}, {[]Commit{{"a", false, nil}}, true}, {[]Commit{{"", true, nil}}, true},
		{[]Commit{{"a", true, nil}, {"a", true, nil}}, true},
		{[]Commit{{"a", true, []Declaration{{Source: "entire", Version: "1", Kind: "checkpoint", Value: "id", Class: Agent, Outcome: "resolved"}}}}, true},
	} {
		if _, err := DeclarationDigest(tc.commits, tc.complete, nil); err == nil {
			t.Fatal("invalid digest input accepted")
		}
	}
	// Invalid bytes remain distinguishable evidence rather than JSON replacement.
	a := ParseGitTrailers("Agent-Session: a:\xff")
	b := ParseGitTrailers("Agent-Session: a:\xfe")
	if a[0].Outcome != InvalidEncoding || b[0].Outcome != InvalidEncoding {
		t.Fatal(a, b)
	}
	da, err := DeclarationDigest([]Commit{{"a", true, a}}, true, nil)
	if err != nil {
		t.Fatal(err)
	}
	db, err := DeclarationDigest([]Commit{{"a", true, b}}, true, nil)
	if err != nil || da == db {
		t.Fatal("invalid byte declarations collapsed")
	}
}
